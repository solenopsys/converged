/**
 * Блоки лендинга приезжают из проекта, а не из ядра, а точка входа поставки
 * одна на все проекты — связывает их этот сгенерированный реэкспорт.
 *
 * Почему файлом, а не резолвом в плагине: путь, выданный плагином, теряет
 * `tsconfig` своего каталога, и JSX проекта молча собирается в react вместо
 * preact — на странице это два несовместимых дерева и падение гидратации.
 * Обычный импорт такого эффекта не даёт.
 *
 * Файл переписывается только при смене проекта: dev-сервер решает, пересобирать
 * ли, по времени правки исходников, и запись «того же самого» гоняла бы сборку
 * по кругу.
 */
async function writeLandingBlocksShim(): Promise<void> {
	const shim = landingBlocksShim();
	const source = relative(dirname(shim), landingBlocksEntry()).replace(
		/\.tsx$/,
		"",
	);
	const contents = [
		"// Сгенерировано сборкой (build/bundles.ts): блоки лендинга проекта-хоста.",
		`export { blocks, BrandLogo, header } from "${source}";`,
		"",
	].join("\n");

	const file = Bun.file(shim);
	if ((await file.exists()) && (await file.text()) === contents) return;
	await Bun.write(shim, contents);
}

async function writeLandingAuditShim(): Promise<void> {
	const shim = landingAuditShim();
	const landing = landingAuditClientEntry("landing");
	const print = landingAuditClientEntry("print");
	const contents =
		landing && print
			? [
					"// Generated by build/bundles.ts: project audit route module.",
					"export const hasAuditPage = true;",
					`export { bootstrapAudit } from "${relative(dirname(shim), landing).replace(/\.tsx$/, "")}";`,
					`export { bootstrapAuditPrint } from "${relative(dirname(shim), print).replace(/\.ts$/, "")}";`,
					"",
				].join("\n")
			: [
					"// Generated by build/bundles.ts: this project has no audit route.",
					"export const hasAuditPage = false;",
					"export const bootstrapAudit = () => {};",
					"export const bootstrapAuditPrint = () => {};",
					"",
				].join("\n");

	const file = Bun.file(shim);
	if ((await file.exists()) && (await file.text()) === contents) return;
	await Bun.write(shim, contents);
}

/**
 * Оболочка и слой чата — один исходник и один файл. Раздельные чанки ничего не
 * экономили: HTML всё равно предзагружал их все, а `warmUpChat` выполнял слой
 * чата сразу после первого экрана.
 */
export async function bundleApp(): Promise<string[]> {
	await writeLandingBlocksShim();

	const result = await Bun.build({
		entrypoints: [clientEntry],
		outdir: assetsDir,
		naming: { entry: "index.js" },
		target: "browser",
		format: "esm",
		splitting: false,
		external: importMapSpecifiers,
		define: clientBuildDefines,
		minify: true,
		sourcemap: isProduction ? "none" : "linked",
	});

	if (!result.success) {
		throw new AggregateError(result.logs, "Build failed: app");
	}

	return result.outputs
		.map((output) => output.path)
		.filter((path) => path.endsWith(".js"));
}

