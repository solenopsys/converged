/**
 * Один микрофронтенд — один чанк. Всё общее (preact, effector, front-core,
 * транспорт) остаётся external: карта импорта уже ведёт эти имена в vendor,
 * дублировать их в каждом MF нельзя — иначе появится второй каталог функций и
 * второй сокет.
 */
export type MicrofrontendBundle = {
	/** Чанк модуля — его тянет карта импорта по имени `mf-<name>`. */
	script: string;
	/**
	 * CSS, который вытащил бандлер из `import "./View.css"` внутри модуля. Своим
	 * файлом он не поставляется: страница подключает один `assets/mf.css`, и
	 * содержимое вклеивается туда (см. styles.ts). Отдельный файл на модуль
	 * означал бы второй линк и второй раунд-трип на каждый MF.
	 */
	styles: string[];
};

export async function bundleMicrofrontends(): Promise<MicrofrontendBundle[]> {
	const entries = microfrontends.map((name) =>
		join(microfrontendDir(name), "src", "index.ts"),
	);
	if (isProduction || process.env.MICROFRONTEND_CONTRACT === "1") {
		await assertMicrofrontendPublicApi(entries);
	}

	const bundles: MicrofrontendBundle[] = [];
	for (const name of microfrontends) {
		const sourceEntry = join(microfrontendDir(name), "src", "index.ts");
		const localizedEntry = await localizedMicrofrontendEntry(sourceEntry, name);
		const result = await Bun.build({
			entrypoints: [localizedEntry.entrypoint],
			outdir: microfrontendsDir,
			naming: {
				entry: `${name}.[ext]`,
				asset: `assets/${name}-[name]-[hash].[ext]`,
			},
			target: "browser",
			format: "esm",
			splitting: false,
			external: importMapSpecifiers,
			plugins: [localizedEntry.plugin],
			define: clientBuildDefines,
			minify: true,
			sourcemap: isProduction ? "none" : "linked",
		});

		if (!result.success) {
			throw new AggregateError(result.logs, `Build failed: mf-${name}`);
		}

		bundles.push({
			script: join(microfrontendsDir, `${name}.js`),
			styles: result.outputs
				.map((output) => output.path)
				.filter((path) => path.endsWith(".css")),
		});
	}

	return bundles;
}

/**
 * Встраиваемая форма: тот же исходник, другая рамка сборки — один IIFE-файл,
 * без externals и без внешних ассетов. CSS приезжает текстом (loader `text`),
 * файловый воркер — виртуальным модулем: с чужого origin ни отдельный
 * стилевой файл, ни воркер не загрузились бы.
 */
export async function bundleWidget(): Promise<string[]> {
	const result = await Bun.build({
		entrypoints: [widgetEntry],
		outdir: widgetDir,
		naming: "ai-chat.iife.js",
		target: "browser",
		format: "iife",
		minify: true,
		sourcemap: "none",
		loader: { ".css": "text" },
		plugins: [
			{
				name: "inline-store-worker",
				setup(build) {
					build.onResolve({ filter: /^virtual:store-worker$/ }, () => ({
						path: "virtual:store-worker",
						namespace: "store-worker",
					}));
					build.onLoad(
						{ filter: /.*/, namespace: "store-worker" },
						async () => ({
							contents: `export default ${JSON.stringify(
								await Bun.file(storeWorkerBundle).text(),
							)};`,
							loader: "js",
						}),
					);
				},
			},
		],
		define: clientBuildDefines,
	});

	if (!result.success) {
		throw new AggregateError(result.logs, "Build failed: widget");
	}

	return [join(widgetDir, "ai-chat.iife.js")];
}
